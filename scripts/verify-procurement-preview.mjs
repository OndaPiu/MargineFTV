import {createRequire} from 'node:module';
import {homedir} from 'node:os';
import path from 'node:path';
import {readFileSync,mkdirSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const require=createRequire(import.meta.url);
let playwright;
try{playwright=require(process.env.PROCUREMENT_PLAYWRIGHT_MODULE||'playwright');}
catch{playwright=require(path.join(homedir(),'.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright'));}
const {chromium}=playwright;
const base='http://127.0.0.1:5180';
const password=readFileSync('.env.local','utf8').match(/^PROCUREMENT_ACCESS_PASSWORD=(.+)$/m)?.[1];
const expected=JSON.parse(readFileSync('private/procurement/catalog.json','utf8'));
const checks=[];
mkdirSync('output',{recursive:true});
const browser=await chromium.launch({headless:true,executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'});
try{
 const context=await browser.newContext({viewport:{width:1440,height:1100}});
 const page=await context.newPage();const pageErrors=[];
 page.on('pageerror',e=>pageErrors.push(e.message));
 let r=await context.request.get(base+'/api/procurement');assert.equal(r.status(),401);
 r=await context.request.get(base+'/api/procurement/documents/ff-listino-2025-07');assert.equal(r.status(),401);
 checks.push('Catalogo e documenti negati senza sessione');
 r=await context.request.post(base+'/api/procurement',{data:{action:'login',password}});assert.equal(r.status(),403);
 checks.push('Richieste senza origine bloccate');
 await page.goto(base+'/commesse');
 await page.getByLabel('Password riservata').fill(password);
 await page.getByRole('button',{name:'Accedi',exact:true}).click();
 await page.getByRole('heading',{name:'I materiali, con il prezzo giusto.'}).waitFor();
 r=await context.request.get(base+'/api/procurement');
 assert.equal(r.status(),200);const payload=await r.json();
 assert.equal(payload.catalog.offers.length,expected.offers.length);assert.equal(payload.catalog.documents.length,expected.documents.length);
 assert.equal(payload.catalog.offers.filter(o=>o.supplierId==='forniture-fotovoltaiche').length,expected.offers.filter(o=>o.supplierId==='forniture-fotovoltaiche').length);
 checks.push('Conteggi confrontati con il catalogo privato locale');
 await page.screenshot({path:'output/catalogo-desktop.png',fullPage:false});
 const search=page.getByRole('textbox',{name:'Cerca materiali'});
 await search.fill('H1-6.0');
 await page.getByRole('heading',{name:'1 voci trovate',exact:true}).waitFor();
 await page.getByRole('button',{name:'H1-6.0 Wi-Fi',exact:true}).click();
 await page.getByRole('dialog').waitFor();
 const offer=expected.offers.find(o=>o.label==='H1-6.0 Wi-Fi');
 const price=new Intl.NumberFormat('it-IT',{style:'currency',currency:'EUR',maximumFractionDigits:3}).format(offer.purchasePriceCents/100);
 assert.ok((await page.getByRole('dialog').innerText()).includes(price));
 await page.getByRole('button',{name:'Chiudi scheda'}).click();
 checks.push('Ricerca e prezzo Fox scontato corretto');
 await page.getByRole('button',{name:/Aggiungi H1-6.0/}).click();
 await page.getByLabel('Costo materiali previsto (€)').fill('2500');
 await page.screenshot({path:'output/distinta-prova.png',fullPage:false});
 await page.getByRole('button',{name:'Chiudi distinta'}).click();
 await search.fill('WALLBOX-FOX-T');
 await page.getByRole('heading',{name:'2 voci trovate',exact:true}).waitFor();
 assert.equal(await page.locator('tbody').getByText('Da controllare',{exact:false}).count(),2);
 checks.push('Entrambi i prezzi discordanti della wallbox conservati');
 r=await context.request.get(base+'/api/procurement/documents/ff-listino-2025-07');
 assert.equal(r.status(),200);assert.match(r.headers()['content-type'],/pdf/);
 checks.push('Documento consultabile con sessione valida');
 await page.getByRole('button',{name:'Fornitori',exact:true}).click();
 await page.getByRole('heading',{name:'Forniture Fotovoltaiche Srl',exact:true}).waitFor();
 await page.getByRole('heading',{name:'Angolo Solare',exact:true}).waitFor();
 await page.screenshot({path:'output/fornitori.png',fullPage:false});
 await page.getByRole('button',{name:'Flusso operativo',exact:true}).click();
 await page.getByRole('heading',{name:'Piani di pagamento',exact:true}).waitFor();
 assert.match(await page.locator('.p-plans').innerText(),/Deposito cauzionale/);
 await page.screenshot({path:'output/flusso-rate.png',fullPage:false});
 checks.push('Fornitori, marchi e piani rate visibili');
 await page.setViewportSize({width:390,height:844});
 await page.getByRole('button',{name:'Catalogo',exact:true}).click();
 await search.fill('Huawei 6,0');
 await page.screenshot({path:'output/catalogo-mobile.png',fullPage:false});
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth));
 checks.push('Layout mobile senza scorrimento orizzontale della pagina');
 await page.getByRole('button',{name:'Commesse',exact:true}).click();
 assert.equal(await page.getByRole('button',{name:'Avvia commessa',exact:true}).isDisabled(),true);
 checks.push('Anteprima non usa pratiche reali e non simula salvataggi');
 await page.setViewportSize({width:1440,height:1100});
 await page.getByRole('button',{name:'Esci dall’area riservata'}).click();
 await page.getByLabel('Password riservata').waitFor();
 r=await context.request.get(base+'/api/procurement');assert.equal(r.status(),401);
 assert.deepEqual(pageErrors,[]);
 checks.push('Uscita invalida la sessione; nessun errore JavaScript nel browser');
 writeFileSync('output/procurement-qa.json',JSON.stringify({passed:true,checks,pageErrors},null,2)+'\n');
 console.log(JSON.stringify({passed:true,checks}));
}finally{await browser.close();}
